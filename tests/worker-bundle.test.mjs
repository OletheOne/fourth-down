import { readFile, readdir } from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const dir=new URL('../dist/client/_next/static/',import.meta.url);
const file=(await readdir(dir)).find(n=>/^draft\.worker-.*\.js$/.test(n));assert.ok(file,'Production build must emit a separate analysis worker');
const source=await readFile(new URL(file,dir),'utf8');let output;
const chunks=new URL('chunks/',dir);
const page=(await readdir(chunks)).find(n=>/^page-.*\.js$/.test(n));assert.ok(page);
const pageSource=await readFile(new URL(page,chunks),'utf8');
assert.ok(pageSource.includes(file),'Page must reference the emitted worker');
const factory=pageSource.match(/new Worker\(([^;]+?)\)\}/);
assert.ok(factory,'Vite worker factory must be emitted');
assert.ok(!factory[0].includes('file:'),'Worker constructor must not resolve against a server filesystem URL');
assert.match(factory[0],/\/_next\/static\/draft\.worker-/,'Worker URL must be same-origin HTTP asset');
const self={postMessage(value){output=value;}};
vm.runInNewContext(source,{self,console,Date,Map,Set,Math},{timeout:20000});
self.onmessage({data:{players:[],drafted:[],teams:['A','B'],settings:{userTeam:'A',draftSlot:1,scoring:'ppr',mode:'contend',starters:{QB:1,RB:1,WR:1,TE:1,FLEX:1,K:0,DST:0}},context:{draftMode:'traditional'}}});
assert.ok(output.analysis);assert.equal(output.analysis.version,'roster-lookahead-3');assert.ok(output.analysis.warnings.some(w=>w.includes('No players')));
console.log('Production worker bundle message contract passed.');
